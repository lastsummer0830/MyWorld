/**
 * 몸통 무늬 — 흰 바탕에 **등판만** 은회색, 그 위에 검은 띠.
 *
 * ★ 사진을 다시 봐야 하는 부분: 등의 검정은 동글동글한 점이 아니라 **척추를 가로지르는 띠**다.
 *   그래서 잡음을 x축으로만 촘촘하게 준다(점무늬로 뿌리면 달마시안이 된다).
 * ★ 등판 경계는 반드시 흔들어야 한다. 매끈한 선으로 자르면 색칠이 아니라 스티커가 된다.
 */
const bodyPaint: PaintFn = (out, p, u, a) => {
  const up = Math.cos(a); //  1 = 등, −1 = 배
  // 흰 배·다리와 코트가 갈리는 높이를 몸통 위치마다 **계단으로** 바꾼다.
  // 매끈하게 바꾸면 다시 그라데이션이다 — 이 스타일의 경계는 꺾인 직선이어야 한다.
  const edge = p.x > 0.02 ? 0.30 : p.x > -0.20 ? -0.20 : 0.10;
  out.copy(up > edge ? cSilver : cWhite);
  // 등 한가운데 짙은 안장 — 얼룩이 아니라 **하나의 큰 색면**이다.
  if (up > 0.5 && p.x < 0.22 && p.x > -0.32) out.copy(cMerle);
};


// ── 갈기(러프) ──────────────────────────────────────────────────
//
// 셸티의 인상은 8할이 이것이다 — 머리보다 넓게 퍼져 얼굴을 액자처럼 감싸는 흰 갈기.
//
// ★★ 3차 수정 — 여기가 "가슴에 베개를 매단" 진범이었다.
//   2차까지 갈기의 **축을 앞뒤(수평)로** 뒀다. 그러면 단면이 세로 원반이 되고, 반경을 키울수록
//   목을 감싸는 **넥카라(엘리자베스 칼라)** 가 된다. 4면도의 top view에서 정확히 그 모양이었다.
//   사진의 갈기는 목을 감는 고리가 아니라 **턱 밑에서 가슴 앞으로 쏟아져 내리는 턱받이**다.
